-- 삭제된 보드 배제용 인덱스.
--
-- 새 파일로 둔 이유: V7은 "파라미터로 넘어오는 조건을 부분 인덱스 술어에 두면 안 된다"는
-- 함정을 다루고, 이건 "드문 쪽을 인덱싱한다"는 다른 이야기다. 그리고 V7은 이미 적용된
-- 마이그레이션이라 고치면 체크섬이 어긋나 DB를 통째로 다시 만들어야 한다.
--
-- 항상 빈 DB에서 시작하므로(docker compose down -v) DROP 없이 추가만 한다.


-- ─────────────────────────────────────────────────────────────
-- 왜 "살아있는 쪽"이 아니라 "삭제된 쪽"을 인덱싱하는가
-- ─────────────────────────────────────────────────────────────
--
-- 취향 벡터 재계산은 좋아요를 누를 때마다 findLikedBoardsWithTime을 부르고, 그 쿼리는
-- 삭제된 보드의 좋아요를 걸러내야 한다. 원래는 이렇게 적혀 있었다.
--
--   WHERE f.user.id = ? AND f.rating = ? AND f.board.deletedAt IS NULL
--
-- 이 조건은 board와의 조인을 유발한다. 그런데 살아있는 보드는 사실상 전부라서, 플래너가
-- board 전체를 훑거나(Seq Scan) 좋아요 건수만큼 PK를 조회한다(Nested Loop). 어느 쪽이든
-- 비용이 O(전체 보드 수)다. 좋아요 한 번마다 도는 경로에서 이건 그대로 누적된다.
--
-- board(id) WHERE deleted_at IS NULL 같은 부분 인덱스는 답이 아니다. 실측해보면 플래너가
-- 아예 쓰지 않는다 — 삭제가 0건이면 그 인덱스가 전체 행을 담으므로, 테이블만큼 큰 인덱스를
-- 훑느니 힙을 훑는 것이 싸다고 판단한다. 삭제가 적을수록 더 안 듣는다.
--
-- 그래서 조건을 뒤집었다. 삭제된 보드는 극소수이므로 그쪽을 인덱싱해 NOT EXISTS로 배제하면
-- 비용이 O(삭제된 보드 수)가 된다. 이 인덱스는 삭제된 행만 담으므로 거의 비어 있다.
--
-- 실측 (board 100,010행 / 삭제 100건 / 사용자당 좋아요 159건, 제네릭 플랜 강제):
--
--   조인 방식   Nested Loop -> board_pkey 159회 조회        buffers 480   0.629ms
--   이 방식     Hash Anti Join -> 삭제된 100건만 읽음       buffers   8   0.090ms
--
--   인덱스 크기 16 kB (board가 10만 행일 때)
--
-- deleted_at IS NOT NULL을 술어에 남겨도 되는 이유는 V7과 같다 — 쿼리에 상수로 박혀 있어
-- 플래너가 매칭을 증명할 수 있다. 파라미터에 의존하는 술어만 문제다.
--
-- 참고: 소프트 삭제는 아직 구현돼 있지 않다(board.deleted_at을 설정하는 코드가 없다).
-- 즉 이 조인은 지금 단 한 행도 걸러내지 않으면서 비용만 내고 있었다. 이 인덱스는 미래를 위한
-- 대비가 아니라 현재 내고 있는 비용을 없애는 것이다.
--
-- 나중에 소프트 삭제를 구현할 때 board_feedback도 함께 정리하면(cascade) 이 배제 자체가
-- 필요 없어진다. 그때 이 인덱스는 2버퍼짜리 무해한 잔재로 남으므로 지워도 되고 둬도 된다.

CREATE INDEX idx_board_deleted
    ON board (id)
    WHERE deleted_at IS NOT NULL;
